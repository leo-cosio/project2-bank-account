const handleLogin = http.post(`${API}/login`, async ({ request }) => {
  const login = await request.json();

  const user = users.find(
    (user) =>
      user.credentials.email === login.email &&
      user.credentials.password === login.password,
  );

  if (!user) {
    return HttpResponse.json(
      { message: "Invalid username or password" },
      { status: 401 },
    );
  }

  return HttpResponse.json(user);
});

const handleTransaction = http.post(
  `${API}/new-transaction`,
  async ({ request }) => {
    const transaction = await request.json();
    const { uid, ...newTransaction } = transaction;
    const user = users.find((user) => user.uid === uid);

    if (!user)
      return HttpResponse.json({ message: "User not found!" }, { status: 401 });

    newTransaction.id = user.transactions.length + 1;
    user.balance += newTransaction.amount;

    user.transactions.push(newTransaction);

    return HttpResponse.json(
      { message: "New transaction created!" },
      { status: 201 },
    );
  },
);

const worker = setupWorker(handleLogin, handleTransaction);
export default worker;
